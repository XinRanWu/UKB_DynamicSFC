# 01_extract_ukb_tabular_data.R
#
# Minimal UK Biobank tabular-data extraction script for the Dynamic SFC study.
#
# Purpose
# -------
# This script documents the UK Biobank tabular fields required by the analyses
# and extracts them from a legacy downloaded UKB bulk table. The original study
# was performed before migration to the UK Biobank Research Analysis Platform
# (RAP), so this script reproduces the legacy tabular extraction step rather
# than providing a RAP-native workflow.
#
# Important
# ---------
# 1. No participant-level UKB data are distributed with this repository.
# 2. Users must have their own authorized UK Biobank data access.
# 3. Column naming differs across historical UKB export/conversion tools.
#    The helper below recognizes several common formats and preserves the
#    original source column names in the extracted files.
# 4. Imaging-derived variables (e.g., SFC/DSFC, TIV, MRI scaling, head motion,
#    SNR) and genetic-derived variables (PRS/APOE genotype) are generated by
#    separate pipelines and are therefore not reconstructed here.

library(data.table)

# -------------------------------------------------------------------------
# User configuration
# -------------------------------------------------------------------------

bulk_file <- Sys.getenv("UKB_BULK_FILE", unset = "PATH/TO/UKB_BULK_TABLE.csv")
output_dir <- Sys.getenv("UKB_EXTRACT_DIR", unset = "derived/tabular")

if (!file.exists(bulk_file)) {
  stop(
    "UKB bulk table not found. Set environment variable UKB_BULK_FILE ",
    "to the authorized local UK Biobank tabular export."
  )
}

dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)

