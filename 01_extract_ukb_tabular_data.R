  outcomes = sort(unique(outcome_fields)),
  lifestyle = sort(unique(lifestyle_fields)),
  genetic_covariates = sort(unique(genetic_covariate_fields)),
  rfmri_covariates = sort(unique(rfmri_covariate_fields))
)

all_required_fields <- sort(unique(unlist(field_groups)))

# -------------------------------------------------------------------------
# Helpers
# -------------------------------------------------------------------------

# Return TRUE for a column belonging to a UKB field ID.
# Supported examples include:
#   21003-2.0
#   21003.2.0
#   f.21003.2.0
#   x21003_2_0
column_matches_field <- function(column_name, field_id) {
  patterns <- c(
    paste0("^", field_id, "[-\\.]"),
    paste0("^f\\.", field_id, "\\."),
    paste0("^x", field_id, "_"),
    paste0("^", field_id, "$")
  )
  any(vapply(patterns, grepl, logical(1), x = column_name))
}

select_columns_for_fields <- function(column_names, field_ids) {
  keep <- column_names %in% c("eid", "FID", "IID")
  for (field_id in field_ids) {
    keep <- keep | vapply(
      column_names,
      column_matches_field,
      logical(1),
      field_id = field_id
    )
  }
  column_names[keep]
}

extract_group <- function(dt, field_ids, output_name) {
  selected <- select_columns_for_fields(names(dt), field_ids)

  if (!("eid" %in% selected)) {
    stop(
      "No 'eid' column was detected. Please rename the participant identifier ",
      "column to 'eid' before running this script."
    )
  }

  out <- dt[, ..selected]
  fwrite(out, file.path(output_dir, output_name), na = "NA")
  invisible(out)
}

# -------------------------------------------------------------------------
# Read bulk table and extract study-specific subsets
# -------------------------------------------------------------------------

message("Reading UKB bulk table: ", bulk_file)
ukb <- fread(bulk_file, showProgress = TRUE)

message("Extracting demographic/general covariates...")
extract_group(
  ukb,
  field_groups$basic,
  "UKB_basic_fields.csv"
)

message("Extracting cognitive/health outcome fields used by the analysis code...")
extract_group(
  ukb,
  field_groups$outcomes,
  "UKB_outcome_fields.csv"
)

message("Extracting lifestyle fields...")
extract_group(
  ukb,
  field_groups$lifestyle,
  "UKB_lifestyle_fields.csv"
)

message("Extracting genetic covariate fields...")
extract_group(
  ukb,
  field_groups$genetic_covariates,
  "UKB_genetic_covariate_fields.csv"
)

message("Extracting rfMRI acquisition/quality covariates...")
extract_group(
  ukb,
  field_groups$rfmri_covariates,
  "UKB_rfmri_covariate_fields.csv"
)

# -------------------------------------------------------------------------
# Field manifest
# -------------------------------------------------------------------------
# A machine-readable manifest is written for provenance and repository review.

field_manifest <- rbindlist(
  lapply(names(field_groups), function(group_name) {
    data.table(
      group = group_name,
      field_id = field_groups[[group_name]]
    )
  })
)

fwrite(
  field_manifest,
  file.path(output_dir, "UKB_field_manifest.csv")
)

# Report fields that were requested but not found in this particular export.
available_columns <- names(ukb)
missing_fields <- all_required_fields[
  !vapply(
    all_required_fields,
    function(id) any(vapply(
      available_columns,
      column_matches_field,
      logical(1),
      field_id = id
    )),
    logical(1)
  )
]

if (length(missing_fields) > 0) {
  warning(
    "The following requested UKB field IDs were not detected in the supplied ",
    "bulk table: ",
    paste(missing_fields, collapse = ", "),
    ". This may reflect a different UKB export/application or column naming scheme."
  )
}

message("Extraction complete. Files written to: ", normalizePath(output_dir))
